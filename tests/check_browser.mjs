// Run with Playwright installed in the caller's environment.
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH}: {})});
const page = await browser.newPage({viewport:{width:1280,height:1100}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const base = resolve(process.argv[2] || 'output');
await page.goto(pathToFileURL(resolve(base,'kidney/explorer.html')).href);
if(await page.locator('#samples').innerText() !== '277') throw Error('Wrong kidney archive compartment count');
await page.locator('#gene').selectOption('A2M');
await page.locator('#compartment').selectOption('glomerulus');
const count=await page.locator('#body tr').count();
if(!count || count >= 277) throw Error('Compartment filter did not reduce rows');
const download=page.waitForEvent('download');
await page.locator('#export').click();
const file=await download;
await file.saveAs(resolve(base,'browser-view-export.json'));
await page.locator('#upload').setInputFiles(resolve(base,'endometriosis/evidence.json'));
await page.waitForFunction(()=>document.querySelector('#samples').textContent === '60');
if(await page.locator('#participants').innerText() !== '5') throw Error('Wrong participant count');
await page.locator('#gene').selectOption('C3');
await page.locator('#compartment').selectOption('Macrophages');
if(await page.locator('#body tr').count() !== 20) throw Error('Endometriosis filter failed');
await page.screenshot({path:resolve(base,'desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:900});
await page.screenshot({path:resolve(base,'mobile.png'),fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Page overflows on mobile');
await page.locator('#upload').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schema_version":1}')});
await page.waitForFunction(()=>document.querySelector('#error').textContent.length>0);
if(await page.locator('#samples').innerText() !== '60') throw Error('Invalid upload changed dataset');
if(errors.length)throw Error(errors.join('\n'));
const result={status:'pass',checks:['kidney inventory','gene selection','compartment filtering','JSON download','endometriosis upload','participant counts','invalid upload preserves data','mobile overflow','no runtime errors']};
await writeFile(resolve(base,'browser-checks.json'),JSON.stringify(result,null,2));
await browser.close();
console.log(JSON.stringify(result));
